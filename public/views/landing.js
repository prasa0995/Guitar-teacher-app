function heroMockup() {
  const card = h('div', { class: 'landing-mock' });
  card.appendChild(h('div', { class: 'landing-mock__bar' }, [
    h('span', { class: 'dot' }), h('span', { class: 'dot' }), h('span', { class: 'dot' }),
    h('span', { class: 'muted', style: 'margin-left:auto;font-size:11px;' }, 'Wonderwall — Verse'),
  ]));
  card.appendChild(h('div', { class: 'landing-mock__chord' }, 'Em7'));
  card.appendChild(h('div', { class: 'muted', style: 'text-align:center;font-size:12px;' }, 'Next: G'));
  const dots = h('div', { class: 'beat-dots', style: 'margin:14px 0;' });
  for (let i = 0; i < 4; i++) dots.appendChild(h('div', { class: 'beat-dot' + (i === 1 ? ' active' : '') }));
  card.appendChild(dots);
  const strum = h('div', { class: 'strum-seq', style: 'justify-content:center;' });
  ['↓', '↓', '↑', '↑', '↓', '↑'].forEach((a, i) => {
    strum.appendChild(h('div', { class: 'beat' + (i === 2 ? ' active' : '') }, [h('div', { class: 'arrow' }, a)]));
  });
  card.appendChild(strum);
  return card;
}
