const STEPS = [
  { n: '01', title: 'Tell us where you\'re starting', desc: 'A quick onboarding on your experience, goals, and the chords/techniques you already know.' },
  { n: '02', title: 'Learn at your own pace', desc: 'Curriculum, chord library, and theory — introduced progressively, never overwhelming.' },
  { n: '03', title: 'Play real songs, guided live', desc: 'Open any song and the app shows exactly which chord, and which strum, right when you need it.' },
];

const STATS = [
  [86, '', 'chords in the library'],
  [0, '∞', 'songs, generated by AI'],
  [24, '/7', 'AI tutor availability'],
  [0, '$0', 'to get started'],
];

const MARQUEE_ITEMS = ['Chords', 'Theory', 'Songs', 'Rhythm', 'Tuner', 'Metronome', 'AI Tutor', 'Practice Plans', 'Progress Tracking', 'Fretboard'];

export function render(root, onGetStarted) {
  const page = h('div', { class: 'landing' });

  page.appendChild(h('nav', { class: 'landing-nav' }, [
    h('div', { class: 'landing-nav__brand' }, ['🎸 AI Guitar', h('span', {}, 'Sensei')]),
    h('div', { class: 'row' }, [
      h('button', { class: 'ghost', onclick: () => onGetStarted('login') }, 'Log in'),
      h('button', { class: 'primary', onclick: () => onGetStarted('signup') }, 'Get Started Free'),
    ]),
  ]));

  const hero = h('section', { class: 'landing-hero' });
  const heroText = h('div', { class: 'landing-hero__text' }, [
    h('div', { class: 'landing-eyebrow' }, '✨ AI-Powered Guitar Learning'),
    h('h1', {}, ['Unleash the ', h('span', { class: 'grad-text' }, 'Guitarist'), ' in You']),
    h('p', { class: 'landing-hero__sub' }, "The only guitar app that actually teaches — chords, theory, songs, and rhythm, guided live by AI, personalized to exactly how you learn."),
    h('div', { class: 'row wrap', style: 'margin-top:8px;' }, [
      h('button', { class: 'primary landing-cta', onclick: () => onGetStarted('signup') }, 'Start Learning Free →'),
      h('button', { class: 'ghost landing-cta', onclick: () => document.getElementById('landing-features').scrollIntoView({ behavior: 'smooth' }) }, 'See how it works'),
    ]),
    h('p', { class: 'muted', style: 'font-size:12.5px;margin-top:14px;' }, 'No credit card. No app store. Just open the link and play.'),
  ]);
  hero.appendChild(heroText);
  hero.appendChild(h('div', { class: 'landing-hero__visual' }, [heroMockup()]));
  page.appendChild(hero);

  // Marquee ticker
  const track = h('div', { class: 'landing-marquee__track' });
  [...MARQUEE_ITEMS, ...MARQUEE_ITEMS].forEach((item, i) => {
    track.appendChild(h('div', { class: 'landing-marquee__item' }, [item, h('span', { class: 'sep' }, '✦')]));
  });
  page.appendChild(h('div', { class: 'landing-marquee' }, [track]));

  // Stats bar (count-up on reveal)
  const statsBar = h('section', { class: 'landing-stats reveal-stagger' });
  const statEls = STATS.map(([target, suffix, label]) => {
    const numEl = h('div', { class: 'landing-stat__num' }, suffix && !target ? suffix : '0');
    numEl.dataset.target = target;
    numEl.dataset.suffix = suffix;
    statsBar.appendChild(h('div', { class: 'landing-stat' }, [numEl, h('div', { class: 'landing-stat__label' }, label)]));
    return numEl;
  });
  page.appendChild(statsBar);

  // Photo section — real people, real guitars
  const photoSection = h('section', { class: 'landing-section reveal' }, [
    h('div', { class: 'landing-section__head' }, [
      h('div', { class: 'landing-eyebrow' }, 'REAL PEOPLE, REAL PROGRESS'),
      h('h2', {}, 'This could be you, in a few weeks.'),
      h('p', { class: 'muted' }, "Every guitarist started exactly where you are now — the difference is having a teacher who's actually paying attention."),
    ]),
    h('div', { class: 'landing-photo-grid' }, [
      photoCard('images/hands-fretboard.jpg', 'Clean chord shapes, built one finger at a time'),
      photoCard('images/window-light.jpg', 'A few minutes a day, at your own pace'),
      photoCard('images/stage-silhouette.jpg', 'Every stage performance started as practice'),
    ]),
  ]);
  page.appendChild(photoSection);

  // Features
  const featuresSection = h('section', { class: 'landing-section reveal', id: 'landing-features' }, [
    h('div', { class: 'landing-section__head' }, [
      h('div', { class: 'landing-eyebrow' }, 'EVERYTHING YOU NEED'),
      h('h2', {}, 'Not a chord library with a chatbot bolted on.'),
      h('p', { class: 'muted' }, 'Every feature feeds one AI-driven picture of what you actually know — and what to learn next.'),
    ]),
  ]);
  const featGrid = h('div', { class: 'landing-feature-grid reveal-stagger' });
  FEATURES.forEach((f) => {
    featGrid.appendChild(h('div', { class: 'landing-feature-card' }, [
      h('div', { class: 'landing-feature-card__icon' }, f.icon),
      h('h3', {}, f.title),
      h('p', { class: 'muted' }, f.desc),
    ]));
  });
  featuresSection.appendChild(featGrid);
  page.appendChild(featuresSection);

  // How it works — with a subtle background photo
  const stepsRow = h('div', { class: 'landing-steps reveal-stagger' });
  STEPS.forEach((s) => {
    stepsRow.appendChild(h('div', { class: 'landing-step' }, [
      h('div', { class: 'landing-step__n' }, s.n),
      h('h3', {}, s.title),
      h('p', { class: 'muted' }, s.desc),
    ]));
  });
  const stepsSection = h('section', { class: 'landing-steps-section' }, [
    h('div', { class: 'landing-photo-bg' }, [h('img', { src: 'images/hands-fretboard.jpg', alt: '' })]),
    h('div', { class: 'landing-section' }, [
      h('div', { class: 'landing-section__head' }, [
        h('div', { class: 'landing-eyebrow' }, 'HOW IT WORKS'),
        h('h2', {}, 'From zero to your first song.'),
      ]),
      stepsRow,
    ]),
  ]);
  page.appendChild(stepsSection);

  // Final CTA with background photo
  page.appendChild(h('section', { class: 'landing-final-cta' }, [
    h('div', { class: 'landing-final-cta__bg' }, [h('img', { src: 'images/stage-silhouette.jpg', alt: '' })]),
    h('div', { class: 'landing-final-cta__content reveal' }, [
      h('h2', {}, ['Ready to ', h('span', { class: 'grad-text' }, 'unleash'), ' the guitarist in you?']),
      h('p', { class: 'muted' }, 'Free to start. Your first lesson is a click away.'),
      h('button', { class: 'primary landing-cta', onclick: () => onGetStarted('signup') }, 'Get Started Free →'),
    ]),
  ]));

  page.appendChild(h('footer', { class: 'landing-footer' }, [
    h('div', {}, '🎸 AI GuitarSensei — built for people who want to actually play, not just collect chord charts.'),
    h('div', { class: 'muted', style: 'font-size:12px;margin-top:6px;' }, 'Song chord/rhythm data only — no copyrighted lyrics or recordings are streamed by this app. Photography via Unsplash.'),
  ]));

  root.appendChild(page);

  // Scroll-reveal
  const revealEls = page.querySelectorAll('.reveal, .reveal-stagger');
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });
  revealEls.forEach((el) => io.observe(el));

  // Count-up stats once visible
  const statsIo = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      statsIo.unobserve(entry.target);
      statEls.forEach((el) => {
        const target = parseInt(el.dataset.target, 10);
        const suffix = el.dataset.suffix || '';
        if (!target) { el.textContent = suffix; return; }
        const duration = 1100;
        const start = performance.now();
        function tick(now) {
          const p = Math.min(1, (now - start) / duration);
          const eased = 1 - Math.pow(1 - p, 3);
          el.textContent = Math.round(eased * target) + suffix;
          if (p < 1) requestAnimationFrame(tick);
        }
        requestAnimationFrame(tick);
      });
    });
  }, { threshold: 0.4 });
  statsIo.observe(statsBar);
}

function photoCard(src, caption) {
  return h('div', { class: 'landing-photo' }, [
    h('img', { src, alt: caption, loading: 'lazy' }),
    h('div', { class: 'landing-photo__caption' }, caption),
  ]);
}

function heroMockup() {
  const card = h('div', { class: 'landing-mock' });
  card.appendChild(h('div', { class: 'landing-mock__bar' }, [
    h('span', { class: 'dot' }), h('span', { class: 'dot' }), h('span', { class: 'dot' }),
    h('span', { class: 'muted', style: 'margin-left:auto;font-size:11px;' }, 'Wonderwall — Verse'),
  ]));
  card.appendChild(h('div', { class: 'landing-mock__chord' }, 'Em7'));
  card.appendChild(h('div', { class: 'muted', style: 'text-align:center;font-size:12px;' }, 'Next: G'));
  const dots = h('div', { class: 'beat-dots', style: 'margin:14px 0;' });
  for (let i = 0; i < 4; i++) dots.appendChild(h('div', { class: 'beat-dot' + (i === 1 ? ' active' : '') }));
  card.appendChild(dots);
  const strum = h('div', { class: 'strum-seq', style: 'justify-content:center;' });
  ['↓', '↓', '↑', '↑', '↓', '↑'].forEach((a, i) => {
    strum.appendChild(h('div', { class: 'beat' + (i === 2 ? ' active' : '') }, [h('div', { class: 'arrow' }, a)]));
  });
  card.appendChild(strum);
  return card;
}
